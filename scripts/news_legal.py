"""新聞貼文法遵自動檢查（2026-10-28，依 docs/marketing/posts/2026-10-28-news/legal_review.md 的過稿標準做成程式）。

兩步：
  1. sanitize(text)：可以安全改寫的字眼直接換掉（「大漲」→「上漲」、「狂賣」→「賣超」…），只改語氣、不改事實。
  2. check(text)：改寫後仍出現的禁用字眼 → 回傳違規清單；有任何一筆，該篇一律不排程（scripts/social_news.py）。

標準（legal_review.md）：不給買賣建議、不寫利多利空、不推論股價、不給目標價、副標問句不暗示漲跌、
傳聞不發、不寫「買進後」情境、不拿美股推台股開盤。這是風險盤點的程式化，不是法律意見。
"""
from __future__ import annotations

import re

# 可直接改寫的誇飾字（只改語氣，不改事實）
REPLACE = [
    ("大漲", "上漲"), ("飆漲", "上漲"), ("狂漲", "上漲"), ("噴漲", "上漲"), ("暴漲", "上漲"), ("勁揚", "上漲"),
    ("大跌", "下跌"), ("暴跌", "下跌"), ("重挫", "下跌"), ("崩跌", "下跌"), ("狂跌", "下跌"), ("慘跌", "下跌"),
    ("狂賣", "賣超"), ("大賣", "賣超"), ("狂買", "買超"), ("大買", "買超"), ("爆量", "量增"),
    ("暴增", "增加"), ("飆升", "上升"), ("飆至", "升至"), ("飆到", "升到"), ("飆", "升至"), ("追捧", "認購"), ("大增", "增加"), ("驟減", "減少"), ("賺翻", "獲利增加"), ("加碼", "增加"), ("減碼", "減少"),
]

# 改寫後仍出現就擋（每條：正則、原因）
FORBID = [
    (r"買進|賣出|買入|賣掉|進場|出場|抄底|追高|停損|停利", "買賣建議字眼"),
    (r"布局|佈局|逢低|逢回|逢高|上車|下車|卡位|搶進", "操作暗示"),
    (r"目標價|評等|調升評級|調降評級|喊價|上看|下看", "目標價／評等"),
    (r"利多|利空|強勁|亮眼|看好|看壞|看旺|樂觀|悲觀|有望|可望|沾光|受惠|題材發酵", "利多利空／評價字眼"),
    (r"必漲|必跌|會漲|會跌|將漲|將跌|漲勢可期|後市|飆股|妖股|主升段|起漲|蜜月行情", "股價推論"),
    (r"建議|推薦|操作策略|教戰|怎麼操作|這樣操作|投資機會", "投資建議"),
    (r"傳出|傳聞|據傳|市場傳|搶單|耳語|小道消息", "傳聞（一律不發）"),
    (r"台股開盤.*(看|推|預估)|(看|推|預估).*台股開盤|今天開盤前可對照", "拿美股推台股開盤"),
    (r"會漲嗎|會跌嗎|能買嗎|該買|該賣|值得買", "問句暗示漲跌或買賣"),
    (r"保證|穩賺|零風險|翻倍賺", "保證獲利"),
    (r"留意|拋售|殺盤|恐慌|崩盤|血洗|慘賠|！？", "情緒字眼或操作暗示"),
]
# 業配／活動／非市場新聞：選題階段就排掉
NOT_NEWS = r"抽獎|抽好禮|購物金|好禮|應援|開戶|優惠|贈|活動|講座|徵才|招募|贊助|頒獎|殊榮|獎項|得獎|行事曆|公益|捐"


# 「營收飆44%」是「成長 44%」不是「升至 44%」（2026-10-29 第二輪：康寧「AI 光通訊營收飆 44%」被改寫成「升至 44%」，意思變成營收＝44%）
GROWTH_FLY = re.compile(r"(營收|獲利|淨利|純益|出貨|業績|訂單|銷售|銷量|EPS|營業利益)([^，。；\d]{0,4}?)飆(?:升|漲)?(\s*[+]?\d[\d,.]*\s*[%％])")


def sanitize(text: str) -> str:
    text = GROWTH_FLY.sub(lambda m: f"{m.group(1)}{m.group(2)}成長{m.group(3)}", text)
    for a, b in REPLACE:
        text = text.replace(a, b)
    return text


def check(text: str) -> list[str]:
    """回傳違規清單（空清單＝通過）。每筆：「原因：命中字」。"""
    out = []
    body = text.replace("非投資建議", "").replace("不構成投資建議", "")
    for pat, why in FORBID:
        m = re.search(pat, body)
        if m:
            out.append(f"{why}：{m.group(0)}")
    if "非投資建議" not in text and "不構成投資建議" not in text:
        out.append("缺法遵句：以上為公開資料整理，非投資建議")
    return out


def clean_ok(text: str) -> bool:
    """單句是否乾淨（不看法遵句）：給選導言句用。"""
    return not any(re.search(p, text) for p, _ in FORBID)


def is_promo(text: str) -> bool:
    return bool(re.search(NOT_NEWS, text))
